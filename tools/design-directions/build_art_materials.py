"""Build deterministic, cached UI palettes from local artwork; never runs in the UI.
Run: python3 tools/design-directions/build_art_materials.py
Requires Pillow. Manual choices preserve the owner-liked Home colours.
"""
from pathlib import Path
import colorsys
import hashlib
import json
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent
OVERRIDES = {'assets/anime0-banner.jpg': '#465471', 'assets/anime1-banner.jpg': '#28484b', 'assets/journal-anime-15-banner.jpg': '#42627c'}

def rgb(hex_value):
    return tuple(int(hex_value[i:i+2], 16)/255 for i in (1,3,5))

def hex_rgb(values):
    return '#' + ''.join(f'{round(max(0,min(1,c))*255):02x}' for c in values)

def mix(a,b,t):
    return tuple(x*(1-t)+y*t for x,y in zip(a,b))

def luminance(values):
    linear = [c/12.92 if c <= .04045 else ((c+.055)/1.055)**2.4 for c in values]
    return sum(c*w for c,w in zip(linear,(.2126,.7152,.0722)))

def material(path):
    key=path.relative_to(ROOT).as_posix()
    with Image.open(path) as source:
        image=ImageOps.exif_transpose(source).convert('RGB')
        # Same aspect ratio as the large Home scene; posters remain uncropped.
        if 'banner' in path.name:
            image=ImageOps.fit(image,(104,32),centering=(.5,.5))
        else:
            image.thumbnail((64,96))
        bins={}
        for pixel in image.getdata():
            h,s,v=colorsys.rgb_to_hsv(*(c/255 for c in pixel))
            if v<.12 or v>.94 or s<.12: continue
            bucket=int(h*24)%24
            bins[bucket]=bins.get(bucket,0)+s*(1-abs(v-.55))
        hue=((max(bins,key=bins.get)+.5)/24) if bins else .4
        base=rgb(OVERRIDES[key]) if key in OVERRIDES else colorsys.hls_to_rgb(hue,.24,.20)
    while (1.05/(luminance(base)+.05))<7:
        base=mix(base,(0,0,0),.05)
    return {'digest':hashlib.sha256(path.read_bytes()).hexdigest()[:16], 'method':'manual-override' if key in OVERRIDES else 'art-hue-v1', 'base':hex_rgb(base), 'deep':hex_rgb(mix(base,(.06,.07,.07),.50)), 'wash':hex_rgb(mix(base,(.98,.98,.96),.92)), 'edge':hex_rgb(mix(base,(.98,.98,.96),.72)), 'ink':'#ffffff', 'contrast':round(1.05/(luminance(base)+.05),2)}

def main():
    paths=sorted({p for pattern in ('anime*.jpg','manga*.jpg','journal-*.jpg','journal-*.png') for p in (ROOT/'assets').glob(pattern)})
    result={p.relative_to(ROOT).as_posix():material(p) for p in paths}
    (ROOT/'instrument-art-materials.js').write_text('// Generated by build_art_materials.py. Palette is keyed to artwork content and has a neutral fallback.\nwindow.KURO_ART_MATERIALS = '+json.dumps(result,indent=2)+';\n')
    print(f'{len(result)} palettes; minimum white contrast {min(x["contrast"] for x in result.values())}:1')

if __name__=='__main__':main()
