    @Test("Every shipped string of the import screens is still a literal in its file", arguments: inventory.map(\.file))
    func stringsKept(file: String) throws {
        let text = try Self.source(file)
        let literals = try #require(Self.inventory.first { $0.file == file }).literals
        #expect(!literals.isEmpty)
        for literal in literals {
            #expect(text.contains("\"" + literal + "\""), "\(file) lost the shipped string \"\(literal)\"")
        }
    }

    @Test("The import button keeps its upper-case literal; the new eyebrow is the only new visible copy")
    func primaryLiteral() throws {
        let text = try Self.source("Kuro/Views/ConciergeView+AniListImport.swift")
        #expect(text.contains("\"READ COMPLETE LIST FOR REVIEW\""))
        #expect(ImportRestyleCopy.aniListEyebrow(german: false) == "Import · AniList")
        #expect(ImportRestyleCopy.aniListEyebrow(german: true) == "Import · AniList")
    }

    @Test("No black pills or serif titles remain on the import screens")
    func noPillsOrSerif() throws {
        for file in Self.inventory.map(\.file) {
            let text = try Self.source(file)
            #expect(!text.contains("design: .serif"), "\(file) still sets a serif title")
            #expect(!text.contains("Capsule(style: .continuous)"), "\(file) still draws capsule pills")
            #expect(!text.contains("kuroBlack.opacity(0.8"), "\(file) still fills black pills")
        }
    }

    @Test("Check options keep their binding and are unique per grid")
    @MainActor
    func checkOptions() {
        var anime = true
        var manga = false
        let options = [
            ImportCheckOption(title: "Anime", isOn: .init(get: { anime }, set: { anime = $0 })),
            ImportCheckOption(title: "Manga", isOn: .init(get: { manga }, set: { manga = $0 }))
        ]
        #expect(Set(options.map(\.id)).count == options.count)
        options[1].isOn.wrappedValue.toggle()
        options[0].isOn.wrappedValue.toggle()
        #expect(manga)
        #expect(!anime)
    }
